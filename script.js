
const lockerStatus = document.getElementById("lockerStatus");
const statusMessage = document.getElementById("statusMessage");

const securityStatus = document.getElementById("securityStatus");
const securityMessage = document.getElementById("securityMessage");

const smsMessage = document.getElementById("smsMessage");
const attemptCount = document.getElementById("attemptCount");

const alarmBox = document.getElementById("alarmBox");
const alarmMessage = document.getElementById("alarmMessage");

const historyList = document.getElementById("historyList");

// The physical Arduino keypad handles these operations.
// Hide the website's old simulation controls.
[
    "generateBtn",
    "verifyBtn",
    "relockBtn",
    "tamperBtn",
    "otpInput",
    "clearHistoryBtn"
].forEach(id => {
    const element = document.getElementById(id);
    if (element) element.hidden = true;
});

const otpLabel = document.querySelector('label[for="otpInput"]');
if (otpLabel) otpLabel.hidden = true;

let lastEventCount = 0;

async function updateDashboard() {
    try {
        const response = await fetch("/api/state");

        if (!response.ok) {
            throw new Error("Could not read Arduino data");
        }

        const data = await response.json();

        // Locker status
        lockerStatus.textContent = data.locker;
        lockerStatus.className =
            "status " +
            (data.locker === "LOCKED" ? "locked" : "unlocked");

        statusMessage.textContent =
            data.locker === "LOCKED"
                ? "Locker is locked. Use the physical keypad."
                : "Access granted by the Arduino.";

        // Security status
        securityStatus.textContent = data.security;
        securityStatus.className =
            "status " +
            (data.security === "ALERT" ? "danger" : "safe");

        securityMessage.textContent =
            data.security === "ALERT"
                ? "Tampering detected by hardware!"
                : "No active security alerts.";

        alarmBox.style.background =
            data.security === "ALERT" ? "#fee2e2" : "#f1f5f9";

        alarmMessage.textContent =
            data.security === "ALERT"
                ? "Arduino detected three incorrect OTP attempts."
                : "No active alarm.";

        // Actual OTP generated by Arduino
        smsMessage.textContent = data.otp
            ? "Actual Arduino OTP: " + data.otp
            : "Waiting for an OTP request from the physical keypad.";

        attemptCount.textContent = "Managed by Arduino";

        // Activity history
        historyList.innerHTML = "";

        if (data.events.length === 0) {
            historyList.textContent = "Waiting for hardware activity...";
        }

        data.events.forEach(event => {
            const row = document.createElement("div");
            row.className = "history-item";

            const message = document.createElement("span");
            message.textContent = event.message;

            const time = document.createElement("span");
            time.className = "history-time";
            time.textContent = event.time;

            row.append(message, time);
            historyList.appendChild(row);
        });

    } catch (error) {
        console.error(error);
        smsMessage.textContent =
            "Waiting for connection to Arduino...";
    }
}

// Read hardware updates every half second
updateDashboard();
setInterval(updateDashboard, 500);
